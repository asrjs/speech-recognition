import { inspect } from 'node:util';
import { readFile, writeFile } from 'node:fs/promises';
import { BUILT_IN_MODEL_DESCRIPTORS } from '../dist/presets/descriptors-catalog.js';
import { LANGUAGE_NAMES as parakeetLanguages } from '../dist/presets/parakeet/catalog.js';
import { LANGUAGE_NAMES as canaryLanguages } from '../dist/presets/canary/catalog.js';
import { resolveParakeetArtifactSource } from '../dist/presets/parakeet/manifest.js';
import { resolveCanaryArtifactSource } from '../dist/presets/canary/manifest.js';
import { resolveMedAsrPresetManifest } from '../dist/presets/medasr/manifest.js';
import { resolveNemotronArtifactSource } from '../dist/presets/nemotron/factory.js';
const sources = {};
for (const d of BUILT_IN_MODEL_DESCRIPTORS) {
 const source = d.preset === 'parakeet' ? resolveParakeetArtifactSource(d.modelId)
 : d.preset === 'canary' ? resolveCanaryArtifactSource(d.modelId)
 : d.preset === 'medasr' ? resolveMedAsrPresetManifest(d.modelId)?.source
 : d.preset === 'nemotron' ? resolveNemotronArtifactSource(d.modelId) : undefined;
 if (source) sources[d.modelId] = source;
}
const literal = value => inspect(value, {depth:null, maxArrayLength:null, maxStringLength:null, compact:false, breakLength:100});
const output = '// Generated by scripts/generate-catalog-data.mjs; do not edit.\n'
 + '/* eslint-disable max-lines -- generated catalog snapshot */\n'
 + "import type { BuiltInModelDescriptor } from './descriptors.js';\n"
 + 'export const CATALOG_DESCRIPTORS: readonly BuiltInModelDescriptor[] = ' + literal(BUILT_IN_MODEL_DESCRIPTORS) + ';\n'
 + 'export const CATALOG_LANGUAGES: Readonly<Record<string, string>> = ' + literal({...canaryLanguages, ...parakeetLanguages}) + ';\n'
 + 'const sources = ' + literal(sources) + ' as const;\n'
 + 'const sourceMap = new Map(Object.entries(sources));\n'
 + 'export function getCatalogArtifactSource(modelId: string): ((typeof sources)[keyof typeof sources] & { readonly revision?: string }) | undefined { return sourceMap.get(modelId); }\n';
const target = new URL('../src/presets/catalog-data.generated.ts', import.meta.url);
if (process.argv.includes('--write')) await writeFile(target, output);
else if ((await readFile(target, 'utf8')).replaceAll('\r\n','\n') !== output) {
 throw new Error('Catalog data is stale: compile, run node scripts/generate-catalog-data.mjs --write, then rebuild.');
}
